"""Builds the ridge wolf and ridge boar used by the normal enemy spawns.

Run with Blender in background mode:
  "D:/Blender/blender.exe" --background --python generate_creatures.py

Outputs go next to this script:

* `wolf.glb` - a lean, long-legged wolf facing +Y (Godot -Z after y-up export).
* `boar.glb` - a low, barrel-bodied boar with a shoulder hump and tusks.

The furry body of each creature is built from overlapping primitives, then
voxel-remeshed into one continuous surface so no ball-and-stick seams show.
The body is UV-unwrapped with Smart UV Project and textured with the tiling
fur/hide atlases generated by `make_creature_textures.py`. Eyes, nose, paws,
hooves, tusks and bristles stay as separate detail shells so they keep their
crisp silhouette. The GLB embeds its texture. Each asset keeps its pivot
between the paws at z=0, matching the placement contract in `actor_visual.gd`.
"""

import math
import os
import random

import bpy
from mathutils import Vector

OUT_DIR = os.path.dirname(os.path.abspath(__file__))
TEXTURE_DIR = os.path.normpath(os.path.join(OUT_DIR, "..", "..", "textures"))
random.seed(20261028)


def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for block in (bpy.data.meshes, bpy.data.materials, bpy.data.images):
        for item in list(block):
            if item.users == 0:
                block.remove(item)


def material(name, color, roughness=0.9):
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    return mat


def card_material(name, tint):
    """Alpha-cut fur card material; the runtime swaps in its own scissor material."""
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    bsdf = nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*tint, 1.0)
    bsdf.inputs["Roughness"].default_value = 0.95
    tex = nodes.new("ShaderNodeTexImage")
    tex.image = bpy.data.images.load(os.path.join(TEXTURE_DIR, "fur_card.png"))
    tex.image.pack()
    tex.interpolation = "Linear"
    links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
    links.new(tex.outputs["Alpha"], bsdf.inputs["Alpha"])
    try:
        mat.blend_method = "CLIP"
    except Exception:
        pass
    return mat


def fur_material(name, texture_name):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    bsdf = nodes.get("Principled BSDF")
    bsdf.inputs["Roughness"].default_value = 0.88
    tex = nodes.new("ShaderNodeTexImage")
    tex.image = bpy.data.images.load(os.path.join(TEXTURE_DIR, texture_name))
    tex.image.pack()
    tex.interpolation = "Linear"
    links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
    return mat


def emissive(name, color, strength=2.5):
    mat = material(name, color, 0.4)
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Emission Color"].default_value = (*color, 1.0)
    bsdf.inputs["Emission Strength"].default_value = strength
    return mat


def assign(obj, mat):
    obj.data.materials.clear()
    obj.data.materials.append(mat)


def smooth(obj):
    if obj is None:
        return obj
    for polygon in obj.data.polygons:
        polygon.use_smooth = True
    return obj


def ellipsoid(name, center, scale, mat, segments=18, rings=10):
    bpy.ops.mesh.primitive_uv_sphere_add(
        segments=segments, ring_count=rings, radius=1.0, location=Vector(center)
    )
    obj = bpy.context.object
    obj.name = name
    obj.scale = Vector(scale)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    assign(obj, mat)
    return smooth(obj)


def tapered(name, start, end, radius_start, radius_end, mat, verts=12,
            smooth_shade=True):
    a = Vector(start)
    b = Vector(end)
    direction = b - a
    if direction.length <= 0.001:
        return None
    bpy.ops.mesh.primitive_cone_add(
        vertices=verts,
        radius1=radius_start,
        radius2=radius_end,
        depth=direction.length,
        location=(a + b) * 0.5,
    )
    obj = bpy.context.object
    obj.name = name
    obj.rotation_mode = "QUATERNION"
    obj.rotation_quaternion = direction.to_track_quat("Z", "Y")
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    assign(obj, mat)
    return smooth(obj) if smooth_shade else obj


def box(name, center, size, mat, rotation=(0.0, 0.0, 0.0)):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=Vector(center))
    obj = bpy.context.object
    obj.name = name
    obj.scale = Vector(size)
    obj.rotation_euler = rotation
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    assign(obj, mat)
    return obj


def join(objects, name):
    objects = [obj for obj in objects if obj is not None]
    bpy.ops.object.select_all(action="DESELECT")
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.object.join()
    joined = bpy.context.object
    joined.name = name
    return joined


def remesh_body(obj, voxel_size, decimate_ratio):
    """Fuse overlapping body parts into one continuous fur surface."""
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    remesh = obj.modifiers.new("Remesh", "REMESH")
    remesh.mode = "VOXEL"
    remesh.voxel_size = voxel_size
    remesh.use_smooth_shade = True
    bpy.ops.object.modifier_apply(modifier=remesh.name)
    relax = obj.modifiers.new("Relax", "SMOOTH")
    relax.factor = 0.55
    relax.iterations = 3
    bpy.ops.object.modifier_apply(modifier=relax.name)
    decimate = obj.modifiers.new("Decimate", "DECIMATE")
    decimate.ratio = decimate_ratio
    bpy.ops.object.modifier_apply(modifier=decimate.name)
    smooth(obj)


def unwrap(obj):
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    # Smart project gives every remaining shell its own island, which is right
    # for a procedural mesh with no hand-authored seams.
    bpy.ops.uv.smart_project(
        angle_limit=math.radians(66.0),
        island_margin=0.018,
        area_weight=0.0,
        correct_aspect=True,
        scale_to_bounds=False,
    )
    bpy.ops.object.mode_set(mode="OBJECT")


def finish_asset(name, joined, scale_value, unwrap_asset=True):
    bpy.ops.object.select_all(action="DESELECT")
    joined.select_set(True)
    bpy.context.view_layer.objects.active = joined
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    for vert in joined.data.vertices:
        vert.co *= scale_value
    lowest = min(vert.co.z for vert in joined.data.vertices)
    for vert in joined.data.vertices:
        vert.co.z -= lowest
        # Flat base exactly at 0 so placement never shows a floating rim.
        if vert.co.z < 0.012:
            vert.co.z = 0.0
    if unwrap_asset:
        unwrap(joined)
    path = os.path.join(OUT_DIR, "%s.glb" % name)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_materials="EXPORT",
        export_image_format="AUTO",
    )
    tris = sum(len(poly.vertices) - 2 for poly in joined.data.polygons)
    print("EXPORTED", path, "tris", tris, "verts", len(joined.data.vertices))
    return joined


def tuft(parts, base, direction, length_value, radius, mat, verts=5):
    """A smooth tapered spike, used where a real bristle is wanted (boar spine)."""
    direction = Vector(direction)
    if direction.length < 0.001:
        return
    origin = Vector(base)
    tip = origin + direction.normalized() * length_value
    parts.append(tapered("Tuft", origin, tip, radius, 0.003, mat, verts=verts, smooth_shade=True))


def fur_card(parts, base, growth, outward, width, height_value, mat, name="FurCard"):
    """Two crossed alpha cards showing a clump of hair.

    Opaque cones read as quills and spheres read as bare skin. A pair of quads
    at right angles, cut by the fur-card alpha texture, gives a soft shaggy
    silhouette that still holds up when the camera looks down from above.
    """
    growth_value = Vector(growth)
    if growth_value.length < 0.001:
        return
    growth_value.normalize()
    outward_value = Vector(outward).normalized()
    axis = growth_value.cross(outward_value)
    if axis.length < 0.001:
        axis = growth_value.cross(Vector((1.0, 0.0, 0.0)))
    if axis.length < 0.001:
        axis = growth_value.cross(Vector((0.0, 0.0, 1.0)))
    axis.normalize()
    second_axis = growth_value.cross(axis).normalized()
    origin = Vector(base)
    verts = []
    faces = []
    for width_axis in (axis, second_axis):
        bottom_l = origin - width_axis * (width * 0.5)
        bottom_r = origin + width_axis * (width * 0.5)
        top_l = origin + growth_value * height_value - width_axis * (width * 0.58)
        top_r = origin + growth_value * height_value + width_axis * (width * 0.58)
        index = len(verts)
        verts.extend([tuple(bottom_l), tuple(bottom_r), tuple(top_r), tuple(top_l)])
        faces.append((index, index + 1, index + 2, index + 3))
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.uv_layers.new(name="UVMap")
    quad_uvs = ((0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0))
    for loop_index, uv in enumerate(quad_uvs * 2):
        mesh.uv_layers.active.data[loop_index].uv = uv
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    assign(obj, mat)
    parts.append(obj)


def fur_ring(parts, center, radius_x, radius_z, count, height_value, mat, sweep, seed, width=0.16):
    """Fans clumps around a body ring: neck ruff, shoulder mantle, rump."""
    rng = random.Random(seed)
    for index in range(count):
        angle = 2.0 * math.pi * float(index) / float(count) + rng.uniform(-0.10, 0.10)
        outward = Vector((math.cos(angle), 0.0, math.sin(angle)))
        base = Vector((
            center[0] + math.cos(angle) * radius_x * rng.uniform(0.88, 1.00),
            center[1] + rng.uniform(-0.020, 0.020),
            center[2] + math.sin(angle) * radius_z * rng.uniform(0.88, 1.00),
        ))
        growth = (outward * 0.80 + Vector(sweep)).normalized()
        fur_card(
            parts,
            base,
            growth,
            outward,
            width * rng.uniform(0.80, 1.22),
            height_value * rng.uniform(0.78, 1.20),
            mat,
        )


def fur_line(parts, start, end, count, height_value, mat, direction, seed, width=0.15, jitter=0.012):
    """A line of clumps along the spine or belly, each one fanned slightly."""
    rng = random.Random(seed)
    a = Vector(start)
    b = Vector(end)
    for index in range(count):
        t = float(index) / float(max(count - 1, 1))
        base = a.lerp(b, t) + Vector((
            rng.uniform(-jitter, jitter),
            rng.uniform(-jitter, jitter),
            rng.uniform(-jitter, jitter),
        ))
        growth = (Vector(direction) + Vector((
            rng.uniform(-0.16, 0.16),
            rng.uniform(-0.16, 0.16),
            rng.uniform(-0.12, 0.12),
        ))).normalized()
        outward = Vector((0.0, 0.0, 1.0)) if abs(direction[2]) > abs(direction[1]) else Vector((0.0, 1.0, 0.0))
        fur_card(
            parts,
            base,
            growth,
            outward,
            width * rng.uniform(0.78, 1.24),
            height_value * rng.uniform(0.78, 1.22),
            mat,
        )


def eye_stack(parts, base, normal, socket_radius, iris_radius, pupil_radius,
              socket_mat, iris_mat, pupil_mat):
    """Socket, iris and pupil as three nested spheres.

    One glowing sphere read as a headlight. Recessing a dark socket, then
    pushing a smaller amber iris and a black pupil out along the gaze normal,
    gives a readable eye from the front and the side.
    """
    base = Vector(base)
    normal = Vector(normal).normalized()
    parts.append(ellipsoid("EyeSocket", base, (socket_radius, socket_radius, socket_radius), socket_mat, segments=12, rings=7))
    parts.append(ellipsoid("EyeIris", base + normal * socket_radius * 0.30,
                           (iris_radius, iris_radius, iris_radius), iris_mat, segments=12, rings=7))
    parts.append(ellipsoid("EyePupil", base + normal * socket_radius * 0.66,
                           (pupil_radius, pupil_radius, pupil_radius), pupil_mat, segments=10, rings=6))


def build_wolf():
    fur = fur_material("WolfFur", "wolf_fur.png")
    dark = material("WolfDark", (0.050, 0.045, 0.040), 0.95)
    paw = material("WolfPaw", (0.115, 0.108, 0.096), 0.95)
    claw = material("WolfClaw", (0.30, 0.28, 0.25), 0.45)
    black = material("WolfBlack", (0.020, 0.018, 0.016), 0.40)
    # Guard hairs are modelled as alpha cards, not painted into the hide.
    guard = card_material("FurCardWolf", (0.360, 0.348, 0.318))
    # Amber iris with only enough emission to catch the eye at dusk; the pupil
    # stays black so the eye never blows out into a white dot.
    eye = emissive("WolfEye", (0.95, 0.60, 0.17), 0.75)
    body_parts = []
    # One smooth body: deep chest, long barrel and tucked hindquarters.
    body_parts.append(ellipsoid("Torso", (0.0, 0.00, 0.68), (0.25, 0.48, 0.29), fur))
    body_parts.append(ellipsoid("Chest", (0.0, 0.30, 0.72), (0.27, 0.30, 0.30), fur))
    body_parts.append(ellipsoid("Hind", (0.0, -0.32, 0.66), (0.26, 0.30, 0.27), fur))
    # Thick neck and a raised ruff; the remesh melts them into the shoulders.
    body_parts.append(tapered("Neck", (0.0, 0.40, 0.82), (0.0, 0.66, 0.95), 0.185, 0.145, fur, verts=14))
    body_parts.append(ellipsoid("Mane", (0.0, 0.42, 0.87), (0.220, 0.21, 0.185), fur))
    body_parts.append(ellipsoid("ManeBack", (0.0, 0.28, 0.85), (0.225, 0.23, 0.195), fur))
    # Wolf head: broad cranium with a pronounced stop and a long, deep muzzle.
    body_parts.append(ellipsoid("Head", (0.0, 0.84, 1.01), (0.205, 0.255, 0.205), fur, segments=16, rings=10))
    body_parts.append(ellipsoid("Brow", (0.0, 0.95, 1.06), (0.185, 0.115, 0.135), fur, segments=14, rings=8))
    body_parts.append(tapered("Muzzle", (0.0, 0.97, 0.985), (0.0, 1.235, 0.925), 0.140, 0.072, fur, verts=12))
    body_parts.append(tapered("Jaw", (0.0, 0.96, 0.915), (0.0, 1.16, 0.880), 0.090, 0.052, fur, verts=10))
    for side in (-1.0, 1.0):
        # Upright, triangular ears: big enough to keep their shape after remesh.
        body_parts.append(tapered("Ear", (side * 0.105, 0.845, 1.13), (side * 0.118, 0.818, 1.375), 0.080, 0.006, fur, verts=8))
        for front in (True, False):
            hip_y = 0.30 if front else -0.29
            knee_y = 0.34 if front else -0.39
            ankle_y = 0.36 if front else -0.27
            toe_y = 0.42 if front else -0.20
            x = side * (0.175 if front else 0.19)
            body_parts.append(tapered("UpperLeg", (x, hip_y, 0.64), (x, knee_y, 0.37), 0.082, 0.058, fur, verts=10))
            body_parts.append(tapered("LowerLeg", (x, knee_y, 0.37), (x, ankle_y, 0.135), 0.056, 0.043, fur, verts=9))
            # A short pastern rolls the shin into the foot, so the leg never ends
            # on a visible cut above a separate block.
            body_parts.append(tapered("Pastern", (x, ankle_y, 0.145), (x, toe_y, 0.062), 0.045, 0.052, fur, verts=8))
    # Bushy tail hanging off the rump in four tapering sections, drooping toward
    # the hocks. A short fat cone read as a fifth limb.
    body_parts.append(tapered("TailBase", (0.0, -0.56, 0.82), (0.0, -0.74, 0.76), 0.108, 0.100, fur, verts=12))
    body_parts.append(tapered("TailMid", (0.0, -0.74, 0.76), (0.0, -0.86, 0.64), 0.100, 0.084, fur, verts=11))
    body_parts.append(tapered("TailLow", (0.0, -0.86, 0.64), (0.0, -0.92, 0.48), 0.084, 0.058, fur, verts=10))
    body_parts.append(tapered("TailTip", (0.0, -0.92, 0.48), (0.0, -0.92, 0.33), 0.058, 0.010, fur, verts=9))
    body = join(body_parts, "WolfBody")
    remesh_body(body, 0.018, 0.34)
    unwrap(body)
    details = []
    # --- Face -------------------------------------------------------
    details.append(ellipsoid("Nose", (0.0, 1.262, 0.930), (0.050, 0.040, 0.038), dark, segments=12, rings=7))
    for side in (-1.0, 1.0):
        details.append(ellipsoid("Nostril", (side * 0.019, 1.292, 0.941), (0.011, 0.009, 0.010), black, segments=8, rings=5))
        eye_stack(
            details,
            (side * 0.100, 1.045, 1.012),
            (side * 0.56, 0.82, 0.10),
            0.035, 0.026, 0.0125,
            dark, eye, black,
        )
        # Inner ear: a dark cone set into the front of the fur cone.
        details.append(tapered("EarInner", (side * 0.103, 0.805, 1.150),
                               (side * 0.133, 0.780, 1.335), 0.042, 0.004, dark, verts=7))
    # Rounded paws with three forward claws; boxes read as crates on the grass.
    for side in (-1.0, 1.0):
        for front in (True, False):
            toe_y = 0.425 if front else -0.195
            x = side * (0.175 if front else 0.19)
            details.append(ellipsoid("Paw", (x, toe_y, 0.043), (0.064, 0.100, 0.043), paw, segments=12, rings=7))
            for claw_index in range(3):
                offset = (float(claw_index) - 1.0) * 0.030
                details.append(tapered(
                    "Claw",
                    (x + offset, toe_y + 0.070, 0.030),
                    (x + offset, toe_y + 0.118, 0.004),
                    0.012, 0.002, claw, verts=5, smooth_shade=False,
                ))
    # --- Coat -------------------------------------------------------
    # A winter pelt: a double ruff around the neck and shoulders, hackles down
    # the spine, a hanging belly fringe and a skirt over the rump.
    fur_ring(details, (0.0, 0.53, 0.885), 0.180, 0.170, 14, 0.150, guard, (0.0, -0.90, 0.10), 4177, width=0.17)
    fur_ring(details, (0.0, 0.42, 0.800), 0.215, 0.205, 13, 0.140, guard, (0.0, -0.92, 0.00), 4181, width=0.17)
    fur_line(details, (0.0, 0.64, 1.005), (0.0, 0.00, 0.955), 9, 0.135, guard, (0.0, -0.62, 0.78), 4193, width=0.15)
    fur_line(details, (0.0, 0.24, 0.415), (0.0, -0.26, 0.405), 7, 0.075, guard, (0.0, -0.30, -0.95), 4201, width=0.12)
    fur_ring(details, (0.0, -0.40, 0.690), 0.225, 0.230, 12, 0.130, guard, (0.0, -0.96, -0.10), 4211, width=0.16)
    # Throat and chest apron: the front of the animal is what the player sees
    # head-on during a dodge, so it cannot be bare skin.
    fur_line(details, (0.0, 0.58, 0.870), (0.0, 0.44, 0.620), 6, 0.105, guard, (0.0, 0.28, -0.96), 4221, width=0.15)
    # Cheek fur, brow tufts and a short beard under the jaw.
    for side in (-1.0, 1.0):
        for index in range(4):
            t = float(index) / 3.0
            fur_card(
                details,
                (side * (0.180 - t * 0.026), 0.942 - t * 0.125, 1.028 - t * 0.105),
                (side * 0.62, -0.70, -0.34 - t * 0.10),
                (side * 1.0, 0.0, 0.15),
                0.112,
                0.078 + t * 0.014,
                guard,
            )
        for index in range(2):
            fur_card(
                details,
                (side * (0.078 + index * 0.032), 1.040 - index * 0.035, 1.175 - index * 0.012),
                (side * 0.34, -0.36, 0.87),
                (side * 1.0, 0.0, 0.0),
                0.070,
                0.062,
                guard,
            )
        for index in range(3):
            fur_card(
                details,
                (side * (0.024 + index * 0.024), 1.070 - index * 0.060, 0.888 - index * 0.008),
                (side * 0.20, -0.32, -0.92),
                (side * 1.0, 0.0, 0.0),
                0.060,
                0.058,
                guard,
            )
    # Tail fluff: four rings around the hanging tail make it read as a brush.
    tail_rings = (
        ((0.0, -0.640, 0.800), 0.100),
        ((0.0, -0.760, 0.745), 0.096),
        ((0.0, -0.860, 0.625), 0.078),
        ((0.0, -0.915, 0.455), 0.052),
    )
    for ring_index, (center, ring_radius) in enumerate(tail_rings):
        for spike in range(5):
            angle = 2.0 * math.pi * float(spike) / 5.0 + ring_index * 0.62
            outward = Vector((math.cos(angle), 0.0, math.sin(angle)))
            fur_card(
                details,
                Vector(center) + outward * ring_radius,
                (outward * 0.72 + Vector((0.0, -0.46, -0.30))).normalized(),
                outward,
                0.105,
                0.092,
                guard,
            )
    # Feathering behind the elbows and hocks.
    for side in (-1.0, 1.0):
        for leg_x, joint in ((0.175, 0.375), (0.190, 0.395), (0.175, 0.165), (0.190, 0.175)):
            for index in range(2):
                fur_card(
                    details,
                    (side * (leg_x - 0.010 + index * 0.020), joint + 0.010 - index * 0.018,
                     0.245 if joint > 0.3 else 0.115),
                    (0.0, -0.66, -0.75),
                    (side * 1.0, 0.0, 0.0),
                    0.068,
                    0.052,
                    guard,
                )
    joined = join([body] + details, "Wolf")
    return finish_asset("wolf", joined, 0.90, unwrap_asset=False)


def build_boar():
    hide = fur_material("BoarHide", "boar_hide.png")
    dark = material("BoarDark", (0.060, 0.040, 0.030), 0.95)
    nose = material("BoarNose", (0.135, 0.105, 0.090), 0.45)
    hoof = material("BoarHoof", (0.085, 0.068, 0.055), 0.80)
    tusk = material("BoarTusk", (0.78, 0.71, 0.55), 0.55)
    black = material("BoarBlack", (0.022, 0.016, 0.013), 0.40)
    # Coarse guard hairs as alpha cards, tinted to the hide.
    guard = card_material("FurCardBoar", (0.360, 0.258, 0.170))
    # Small, deep-set amber-brown eyes; a boar's eyes are not lamps.
    eye = emissive("BoarEye", (0.66, 0.40, 0.13), 0.45)
    body_parts = []
    # Low barrel body with a heavy shoulder hump.
    body_parts.append(ellipsoid("Barrel", (0.0, 0.00, 0.60), (0.31, 0.46, 0.30), hide))
    body_parts.append(ellipsoid("Shoulder", (0.0, 0.24, 0.78), (0.29, 0.28, 0.21), hide))
    body_parts.append(ellipsoid("Hind", (0.0, -0.34, 0.60), (0.28, 0.29, 0.27), hide))
    body_parts.append(ellipsoid("Head", (0.0, 0.62, 0.70), (0.20, 0.24, 0.21), hide, segments=16, rings=10))
    body_parts.append(tapered("Snout", (0.0, 0.77, 0.68), (0.0, 1.02, 0.64), 0.150, 0.100, hide, verts=12))
    for side in (-1.0, 1.0):
        # Pricked ears that clear the skull after the remesh pass.
        body_parts.append(tapered("Ear", (side * 0.140, 0.600, 0.860), (side * 0.205, 0.530, 1.075), 0.076, 0.006, hide, verts=8))
        for front in (True, False):
            y = 0.28 if front else -0.30
            x = side * (0.205 if front else 0.215)
            body_parts.append(tapered("UpperLeg", (x, y, 0.58), (x, y + 0.01, 0.31), 0.105, 0.080, hide, verts=10))
            body_parts.append(tapered("LowerLeg", (x, y + 0.01, 0.31), (x, y, 0.125), 0.078, 0.064, hide, verts=9))
    # Short curled tail.
    body_parts.append(tapered("TailBase", (0.0, -0.58, 0.780), (0.0, -0.700, 0.740), 0.055, 0.042, hide, verts=9))
    body_parts.append(tapered("TailTip", (0.0, -0.700, 0.740), (0.0, -0.680, 0.620), 0.042, 0.012, hide, verts=8))
    body = join(body_parts, "BoarBody")
    remesh_body(body, 0.016, 0.34)
    unwrap(body)
    details = []
    # A small nose pad set into the snout, with two slit nostrils.
    details.append(tapered("Nose", (0.0, 1.018, 0.640), (0.0, 1.058, 0.640), 0.074, 0.071, nose, verts=10, smooth_shade=False))
    for side in (-1.0, 1.0):
        details.append(ellipsoid("Nostril", (side * 0.030, 1.061, 0.638), (0.011, 0.007, 0.014), black, segments=8, rings=5))
        eye_stack(
            details,
            (side * 0.108, 0.762, 0.806),
            (side * 0.62, 0.74, 0.16),
            0.030, 0.021, 0.0095,
            dark, eye, black,
        )
        # Inner ear, a dark cup inside the pricked hide cone.
        details.append(tapered("EarInner", (side * 0.150, 0.565, 0.905),
                               (side * 0.196, 0.532, 1.055), 0.040, 0.004, dark, verts=7))
        # Two-segment curved tusk sweeping up and out.
        details.append(tapered("Tusk", (side * 0.105, 0.84, 0.615), (side * 0.140, 1.01, 0.675), 0.036, 0.024, tusk, verts=8))
        details.append(tapered("TuskTip", (side * 0.140, 1.01, 0.675), (side * 0.172, 1.10, 0.815), 0.024, 0.004, tusk, verts=8))
        # Cloven hooves: two horn toes per foot instead of one wide cone.
        for front in (True, False):
            y = 0.30 if front else -0.28
            x = side * (0.205 if front else 0.215)
            for toe in (-1.0, 1.0):
                details.append(tapered(
                    "Hoof",
                    (x + toe * 0.035, y, 0.150),
                    (x + toe * 0.040, y + 0.015, 0.0),
                    0.038, 0.032, hoof, verts=7, smooth_shade=False,
                ))
    # A bristle ridge along the spine, three rows deep at the shoulder: separate
    # flat cones so the remesh cannot melt the spikes back into the body.
    for index in range(11):
        t = float(index) / 10.0
        y = 0.46 - t * 0.70
        base_z = 0.955 - abs(t - 0.26) * 0.22
        height_value = 0.190 - abs(t - 0.28) * 0.15
        details.append(tapered(
            "Bristle",
            (0.0, y, base_z),
            (0.0, y - 0.115, base_z + max(height_value, 0.055)),
            0.034, 0.003, dark, verts=6,
        ))
    for side in (-1.0, 1.0):
        for index in range(8):
            t = float(index) / 7.0
            y = 0.42 - t * 0.62
            base_z = 0.930 - abs(t - 0.26) * 0.20
            details.append(tapered(
                "Bristle",
                (side * 0.090, y, base_z),
                (side * (0.120 + 0.02 * t), y - 0.100, base_z + max(0.110 - abs(t - 0.28) * 0.09, 0.035)),
                0.026, 0.003, dark, verts=5,
            ))
    # --- Hide coat ---------------------------------------------------
    # Coarse shoulder and rump tufts plus a jowl fringe. Shorter and blunter
    # than the wolf's ruff: boars read as bristly, not fluffy.
    fur_ring(details, (0.0, 0.06, 0.610), 0.288, 0.278, 14, 0.085, guard, (0.0, -0.94, -0.24), 5217, width=0.13)
    fur_ring(details, (0.0, -0.30, 0.600), 0.268, 0.258, 12, 0.075, guard, (0.0, -0.96, -0.20), 5223, width=0.12)
    fur_line(details, (0.0, 0.18, 0.315), (0.0, -0.26, 0.312), 7, 0.055, guard, (0.0, -0.40, -0.91), 5231, width=0.10)
    for side in (-1.0, 1.0):
        for index in range(4):
            t = float(index) / 3.0
            fur_card(
                details,
                (side * (0.176 - t * 0.020), 0.712 - t * 0.075, 0.706 - t * 0.042),
                (side * 0.66, -0.68, -0.40 - t * 0.10),
                (side * 1.0, 0.0, 0.20),
                0.072,
                0.048,
                guard,
            )
        # A few coarse hairs off the tail stub.
        fur_card(details, (side * 0.045, -0.700, 0.760), (side * 0.30, -0.76, -0.58),
                 (side * 1.0, 0.0, 0.0), 0.055, 0.040, guard)
    joined = join([body] + details, "Boar")
    return finish_asset("boar", joined, 0.95, unwrap_asset=False)


